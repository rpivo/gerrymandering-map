"""Write the site's data files.

Everything in `site/src/data/` is generated, committed, and never edited by hand:

- `districts.json`: scores for every district.
- `shapes.json`: SVG outlines for every district (a coarse one for cards, a finer one
  for its page) and a map of each state's districts.
- `states.json`: each state's name, seats and the 2026 map details from the audit.
- `population.json`: each district's 2020 voting-age population by race (written by
  `python -m gerry population`).
- `fairness.json`: each state's partisan fairness scores, or why it has none (written by
  `python -m gerry fairness`, not `scores`).

All three are written deterministically (fixed order, rounded numbers, no timestamps),
so rebuilding from the same data gives byte-identical files and diffs show only real
changes.
"""

import json
import math
from pathlib import Path

import geopandas as gpd
import pandas as pd

from gerry.display import display_crop, district_outline, state_map, us_map
from gerry.fairness import MIN_DISTRICTS
from gerry.fetch import CENSUS_CD119
from gerry.places import MAX_PLACES
from gerry.states import STATES_BY_USPS

# Simplification for each drawing, as a share of the shape's longer side.
CARD_DETAIL = 0.01
PAGE_DETAIL = 0.002
STATE_DETAIL = 0.002
# The US map is drawn about 700 pixels wide, so 1/1000 of its width is under a pixel.
US_DETAIL = 0.001

# (output field, source column, decimal places or None for non-floats)
FIELDS: list[tuple[str, str, int | None]] = [
    ("id", "district_id", None),
    ("state", "state", None),
    ("number", "number", None),
    ("at_large", "at_large", None),
    ("redrawn_2026", "redrawn_2026", None),
    ("map_source", "map_source", None),
    ("polsby_popper", "polsby_popper", 4),
    ("reock", "reock", 4),
    ("convex_hull", "convex_hull", 4),
    ("schwartzberg", "schwartzberg", 4),
    ("state_edge_share", "state_edge_share", 3),
    ("polsby_popper_pct", "polsby_popper_pct", 1),
    ("reock_pct", "reock_pct", 1),
    ("convex_hull_pct", "convex_hull_pct", 1),
    ("irregularity", "irregularity", None),
    ("rank_national", "rank_national", None),
    ("rank_state", "rank_state", None),
]
# Missing values are expected only here, and only for at-large districts.
UNRANKED = {"number", "polsby_popper_pct", "reock_pct", "convex_hull_pct", "irregularity",
            "rank_national", "rank_state"}  # fmt: skip


def _plain(value, places: int | None):
    """Convert a pandas value into a JSON type: missing values to None, floats rounded."""
    if value is None or value is pd.NA or (isinstance(value, float) and math.isnan(value)):
        return None
    if isinstance(value, float) and places is not None:
        return round(value, places)
    return value


def district_records(scores: pd.DataFrame) -> list[dict]:
    """Turn scores into plain JSON-ready records, one per district, in input order.

    Raises:
        ValueError: if a value is missing where it shouldn't be (anything outside
            UNRANKED, or an UNRANKED field of a district that isn't at-large).
    """
    frame = scores.assign(redrawn_2026=scores["map_source"] != CENSUS_CD119.id)
    records = []
    for _, row in frame.iterrows():
        record = {field: _plain(row[column], places) for field, column, places in FIELDS}
        missing = [f for f, v in record.items() if v is None]
        allowed = UNRANKED if record["at_large"] else set()
        if set(missing) - allowed:
            raise ValueError(
                f"{record['id']}: missing values for {sorted(set(missing) - allowed)}."
            )
        records.append(record)
    return records


def write_districts_json(scores: pd.DataFrame, path: Path) -> None:
    """Write site/src/data/districts.json for the site to build from."""
    records = district_records(scores)
    data = {
        "description": "Compactness scores for every US congressional district, 2026 map. "
        "Generated by `python -m gerry scores`; do not edit by hand.",
        "count": len(records),
        "fields": [field for field, _, _ in FIELDS],
        "districts": records,
    }
    _write_json(data, path)


def _write_json(data: dict, path: Path) -> None:
    """Write data as stable, indented JSON."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")


def _with_note(drawing: dict, note: str | None) -> dict:
    """Add a note to a drawing when part of the shape was left out of it."""
    return drawing | {"note": note} if note else drawing


def write_shapes_json(districts: gpd.GeoDataFrame, path: Path) -> None:
    """Write site/src/data/shapes.json: district outlines and state maps as SVG paths.

    Drawings use gerry.display.display_crop, and carry its note when it left anything out.
    """
    shown = districts.copy()
    crops = [display_crop(s, g) for s, g in zip(shown["state"], shown.geometry, strict=True)]
    shown["geometry"] = [shape for shape, _ in crops]
    notes = dict(zip(shown["district_id"], (note for _, note in crops), strict=True))
    data = {
        "description": "SVG outlines for every district and state map, 2026 map. "
        "Generated by `python -m gerry scores`; do not edit by hand.",
        "districts": {
            district: _with_note(
                {
                    "card": district_outline(geometry, shown.crs, CARD_DETAIL),
                    "page": district_outline(geometry, shown.crs, PAGE_DETAIL),
                },
                notes[district],
            )  # fmt: skip
            for district, geometry in zip(shown["district_id"], shown.geometry, strict=True)
        },
        "states": {
            state: _with_note(
                state_map(rows.sort_values("district_id"), STATE_DETAIL),
                next((notes[d] for d in sorted(rows["district_id"]) if notes[d]), None),
            )
            for state, rows in shown.groupby("state")
        },
    }
    _write_json(data, path)


def write_us_map_json(states: dict, path: Path) -> None:
    """Write site/src/data/us-map.json: the 50 states as one map, for the home page."""
    data = {
        "description": "The 50 states as one SVG map (Alaska and Hawaii as insets), with a "
        "label point for each. Generated by `python -m gerry scores`; do not edit by hand.",
        **us_map(states, US_DETAIL),
    }
    _write_json(data, path)


AUDIT_FIELDS = ["map_in_effect_2026", "enacted", "drawn_by", "first_used", "source_url",
                "source_publisher", "notes", "confidence", "checked"]  # fmt: skip


def state_records(audit: list[dict[str, str]]) -> list[dict]:
    """Return one record per state: name, seats and its 2026 map details from the audit."""
    records = []
    for row in audit:
        state = STATES_BY_USPS[row["state"]]
        record = {
            "state": state.usps,
            "name": state.name,
            "seats": state.seats,
            "at_large": state.seats == 1,
            "changed_since_2024": row["changed_since_2024"] == "yes",
        }
        record.update({field: row[field] or None for field in AUDIT_FIELDS})
        records.append(record)
    return records


def write_states_json(audit: list[dict[str, str]], path: Path) -> None:
    """Write site/src/data/states.json from the state map audit."""
    records = state_records(audit)
    data = {
        "description": "Each state's seats and the congressional map it used in the 2026 "
        "election. Generated by `python -m gerry scores`; do not edit by hand.",
        "count": len(records),
        "states": records,
    }
    _write_json(data, path)


SOURCE_FIELDS = ["id", "publisher", "description", "url", "license", "downloaded"]


def _source_role(source_id: str) -> str:
    """Return what a source is used for, from its ID prefix."""
    if source_id.startswith("census-tiger-"):
        return "calibration"
    if source_id.startswith("census-pl94171-"):
        return "population"
    votes = source_id.startswith("medsl-") or source_id.endswith("-votes")
    return "votes" if votes else "boundaries"


def write_sources_json(entries: dict[str, dict[str, str]], path: Path) -> None:
    """Write site/src/data/sources.json from the sources manifest, for the methodology page.

    Census TIGER files are used only by `python -m gerry calibrate`, so their role is
    "calibration"; MIT election files (`medsl-`) and other results (`-votes`) supply "votes";
    the 2020 redistricting files (`census-pl94171-`) supply "population";
    every other source supplies boundaries.
    """
    sources = [
        {
            **{field: entries[key][field] for field in SOURCE_FIELDS},
            "role": _source_role(key),
        }
        for key in sorted(entries)
    ]
    _write_json({"description": "Every data source behind the map.", "sources": sources}, path)


# (output field, decimal places or None for non-floats), in output order.
FAIRNESS_FIELDS: list[tuple[str, int | None]] = [
    ("districts", None),
    ("dem_vote_share", 4),
    ("dem_seats", None),
    ("one_party_won_every_district", None),
    ("efficiency_gap", 4),
    ("mean_median", 4),
    ("declination", 4),
    ("method", None),
]


def _unscored_status(row: dict[str, str]) -> str:
    """Say why a state has no fairness scores."""
    seats = STATES_BY_USPS[row["state"]].seats
    if seats == 1:
        return "at_large"
    if seats < MIN_DISTRICTS:
        return "too_few_districts"
    if row["changed_since_2024"] == "yes":
        return "awaiting_2026_results"
    return "no_vote_data"


def fairness_records(table: pd.DataFrame, audit: list[dict[str, str]]) -> list[dict]:
    """Return one fairness record per state in the audit, scored or with the reason it isn't.

    Scores are signed so that positive favors Republicans. Unscored states carry a status
    (at_large, too_few_districts, awaiting_2026_results or no_vote_data) and null scores.
    """
    scored = {r["state"]: r for r in table.to_dict("records")}
    records = []
    for row in audit:
        usps = row["state"]
        record: dict = {"state": usps}
        if usps not in scored:
            record["status"] = _unscored_status(row)
            record.update({field: None for field, _ in FAIRNESS_FIELDS})
        else:
            values = scored[usps]
            seats = int(values["dem_seats"])
            values["one_party_won_every_district"] = seats in (0, int(values["districts"]))
            record["status"] = "scored"
            record.update({f: _plain(values[f], places) for f, places in FAIRNESS_FIELDS})
            record["districts"], record["dem_seats"] = int(values["districts"]), seats
        records.append(record)
    return records


def write_fairness_json(table: pd.DataFrame, audit: list[dict[str, str]], path: Path) -> None:
    """Write site/src/data/fairness.json: partisan fairness scores for every state."""
    records = fairness_records(table, audit)
    data = {
        "description": "Partisan fairness scores for each state's congressional map, from the "
        "2024 presidential vote by district. Positive favors Republicans, negative favors "
        "Democrats. Generated by `python -m gerry fairness`; do not edit by hand.",
        "count": len(records),
        "states": records,
    }
    _write_json(data, path)


# (output share, gerry.population column); minority groups count people alone or in combination.
POPULATION_SHARES = [("hispanic", "hispanic"), ("white", "nh_white"), ("black", "nh_black"),
                     ("aian", "nh_aian"), ("asian", "nh_asian"), ("nhpi", "nh_nhpi"),
                     ("minority", "minority")]  # fmt: skip
MINORITY_GROUPS = ["hispanic", "black", "aian", "asian", "nhpi"]


def population_records(table: pd.DataFrame) -> list[dict]:
    """Return one record per district of 2020 voting-age shares and its majority, if minority.

    Shares are 0 to 1 of the voting-age population (18 and over). `majority` names the
    minority group over half of it, else "coalition" if minority residents together are
    over half, else None.
    """
    records = []
    for row in table.sort_values("district_id").to_dict("records"):
        shares = {name: row[column] / row["vap"] for name, column in POPULATION_SHARES}
        top = max(MINORITY_GROUPS, key=lambda g: shares[g])
        majority = top if shares[top] > 0.5 else "coalition" if shares["minority"] > 0.5 else None
        records.append(
            {"id": row["district_id"], "vap": int(row["vap"])}
            | {name: round(share, 3) for name, share in shares.items()}
            | {"majority": majority}
        )
    return records


def write_population_json(table: pd.DataFrame, path: Path) -> None:
    """Write site/src/data/population.json: each district's voting-age population by group."""
    records = population_records(table)
    data = {
        "description": "Each district's 2020 Census voting-age population by race and Hispanic "
        "origin, as 0 to 1 shares. Generated by `python -m gerry population`; do not edit by hand.",
        "count": len(records),
        "districts": records,
    }
    _write_json(data, path)


def places_records(table: pd.DataFrame, districts: pd.DataFrame) -> list[dict]:
    """Return each district's largest places and how much of it lives in any place.

    Args:
        table: From gerry.places.district_places.
        districts: district_id and pop (2020 population, all ages) for every district.

    Returns:
        One record per district: up to MAX_PLACES places (name, kind, pop in the district,
        place_pop in all), largest in the district first; `more`, how many smaller places
        are left out; and `in_places`, the 0 to 1 share of the district's people in any place.
    """
    records = []
    by_district = dict(tuple(table.groupby("district_id")))
    for row in districts.sort_values("district_id").itertuples():
        mine = by_district.get(row.district_id, table.iloc[:0])
        mine = mine.sort_values(["pop", "name"], ascending=[False, True])
        shown = mine.head(MAX_PLACES)
        records.append({
            "id": row.district_id,
            "places": [
                {"name": p.name, "kind": p.kind, "pop": int(p.pop), "place_pop": int(p.place_pop)}
                for p in shown.itertuples()
            ],
            "more": len(mine) - len(shown),
            "in_places": round(float(mine["pop"].sum()) / row.pop, 3) if row.pop else 0.0,
        })  # fmt: skip
    return records


def write_places_json(table: pd.DataFrame, districts: pd.DataFrame, path: Path) -> None:
    """Write site/src/data/places.json: each district's largest cities, towns and communities."""
    records = places_records(table, districts)
    data = {
        "description": "Each district's largest 2020 Census places (cities, towns and "
        "census-designated communities) by population in the district. Generated by "
        "`python -m gerry population`; do not edit by hand.",
        "count": len(records),
        "districts": records,
    }
    _write_json(data, path)
